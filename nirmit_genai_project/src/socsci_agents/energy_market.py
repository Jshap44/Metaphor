BRANDS = ('Ghost', 'C4', 'Celsius', 'Red Bull', 'Monster', 'Gorilla Mind', 'Alani Nu', 'Rockstar', 'Other')
BUDGETS = ('very_limited', 'limited', 'moderate', 'comfortable', 'very_comfortable')
FIELDS = ('consumer_id','source','occupation','budget','weekly_drinks','favorite_brand',
          'alternative_brand','price_per_serving','max_price_per_serving','loyalty',
          'price_sensitivity','health_concern','sugar_free_only','stock_at_home',
          'substitute_preworkout','convenience_sensitivity','interview_notes')


